"""gunicorn 실행 설정. Render는 시작 명령이 `gunicorn app:app`뿐이라
워커/스레드 수를 별도로 지정하지 않으면 기본값(sync 워커 1개)으로
돈다. gunicorn은 이 파일(저장소 루트의 gunicorn.conf.py)이 있으면
시작 명령을 바꾸지 않아도 자동으로 읽는다.

왜 필요한가: sync 워커는 프로세스 하나가 요청을 한 번에 하나씩만
처리한다. 이 프로젝트는 "한 번도 수집된 적 없는 검색어"를 검색하면
그 자리에서 네이버 API를 최대 약 3초까지 기다리는 기능이 있는데
(README 5.14), sync 워커가 1개뿐이면 이 3초 동안 다른 사용자의
모든 요청(로그인, 다른 검색 등)이 전부 대기열에 묶인다.

왜 워커를 늘리지 않고 스레드로 늘리는가: Render 무료 인스턴스는
512MB로 빠듯하다(README 5.6에 이 한도 때문에 겪은 재시작 장애가
있다). 워커를 여러 개 띄우면 프로세스마다 파이썬 인터프리터와
불러온 라이브러리가 통째로 복제되어 메모리를 그만큼 곱해서 쓰지만,
스레드는 같은 프로세스 안에서 힙(로드된 모듈, 커넥션 풀 등)을
공유하고 스레드별 스택만 추가로 든다 — 메모리 부담이 훨씬 작다.

스레드로 바꿔도 안전한 이유(코드 쪽 확인):
- DB 커넥션 풀이 psycopg2.pool.ThreadedConnectionPool이라 원래부터
  여러 스레드가 동시에 커넥션을 빌려 써도 안전하게 설계되어 있다.
- app.py의 get_kiwi() 전역 캐시는 이중 검사 잠금(threading.Lock)으로
  race condition을 막아뒀다. 다만 현재 배포 환경은
  ENABLE_VISUALIZATIONS=false라 이 경로 자체가 호출되지 않는다.
- matplotlib(pyplot)의 전역 상태는 여러 스레드가 동시에 그림을 그리면
  꼬일 수 있는데, 이것도 ENABLE_VISUALIZATIONS=false인 동안은 호출되지
  않아 지금 배포 환경에서는 해당되지 않는다. 나중에 운영에서도
  시각화를 켠다면 이 부분은 별도로 다시 점검해야 한다.
- 실시간 조회 속도 제한(pg_advisory_xact_lock 기반)은 애초에
  프로세스 경계와 무관하게 DB 레벨에서 직렬화하도록 만들어서 스레드
  여러 개에서도 그대로 정확하다.

threads=4로 정한 이유: 이 정도만 돼도 "느린 요청 하나가 나머지를
전부 막는" 문제는 없어지고, 스레드 스택 메모리 증가분은 몇 MB 수준
(정확한 수치는 측정하지 않음)이라 512MB 한도에서 감당 가능하다고
보수적으로 판단한 값이다. 실제 배포 후 메모리 사용량을 보고 조정할 수
있다.
"""

workers = 1
worker_class = "gthread"
threads = 4

# gunicorn이 워커(스레드 포함)가 이 시간(초) 동안 응답이 없으면 죽었다고
# 보고 재시작한다. 실시간 조회 최악 케이스(약 3초 + DB 왕복)보다 충분히
# 여유 있게 기본값(30초)을 그대로 명시해 둔다.
timeout = 30
